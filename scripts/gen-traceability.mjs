#!/usr/bin/env node
// Generates docs/qa/TRACEABILITY.md: acceptance criteria AC01-AC39 and requirements R001-R036 mapped to the test files / scripts that exercise them.
// It lists WHERE a criterion is exercised. Pass/fail results are recorded in docs/QA_REPORT.md from actual runs.
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const spec = JSON.parse(readFileSync(join(root, 'spec/application_spec.json'), 'utf8'));
const walk = (d, out = []) => { for (const n of readdirSync(d)) { const p = join(d, n); statSync(p).isDirectory() ? walk(p, out) : out.push(p); } return out; };
const tests = walk(join(root, 'tests')).filter((p) => /\.(test|spec)\.js$/.test(p)).map((p) => [relative(root, p), readFileSync(p, 'utf8')]);

// Criteria that are exercised by validators / scripts rather than by an "ACnn" tag in a test title.
const EXTRA = {
  AC14: ['scripts/validate-spec.mjs (V-checks on destinations, regions, prerequisites, route cycles)', 'tests/unit/map.test.js'],
  AC24: ['scripts/lib/checks.mjs A10-A12 (negative fixtures in tests/unit/validators.test.js); zero mocks are released, so the shipped-content check is vacuous'],
  AC26: ['scripts/lib/checks.mjs X02 (negative fixture in tests/unit/validators.test.js)'],
  AC27: ['scripts/license-audit.mjs (runs in every build)', 'tests/unit/license-audit.test.js (negative fixture)'],
  AC36: ['tests/unit/license-audit.test.js (workflow and package.json scan)'],
  AC39: ['scripts/license-audit.mjs; content/assets.manifest.json is empty (no third-party assets); human check H-asset PENDING'],
  AC35: ['tests/e2e/pwa.spec.js covers only the automatable part (manifest, icons, meta tags); real-device install NOT RUN'],
};
const MANUAL = new Set(['AC35']);

const lines = ['# Traceability', '', 'Generated by `node scripts/gen-traceability.mjs`. It lists where each acceptance criterion (AC) is exercised. Pass/fail results from actual runs are in [../QA_REPORT.md](../QA_REPORT.md).', '', '## Acceptance criteria', '', '| AC | Criterion | Requirements | Verification (spec) | Exercised by |', '|---|---|---|---|---|'];
const acs = [...spec.acceptance_criteria].sort((a, b) => a.id.localeCompare(b.id));
const acHits = {};
for (const a of acs) {
  const files = tests.filter(([, t]) => new RegExp(`\\b${a.id}\\b`).test(t)).map(([f]) => f);
  const extra = EXTRA[a.id] || [];
  acHits[a.id] = [...files, ...extra];
  const by = acHits[a.id].length ? acHits[a.id].map((x) => `\`${x}\``.replace(/`\(/, '(')).join('<br>') : '**NO TEST FOUND**';
  lines.push(`| ${a.id} | ${a.criterion.replace(/\|/g, '/')} | ${(a.requirements || []).join(', ')} | ${a.verification} | ${MANUAL.has(a.id) ? '**PARTLY NOT RUN (manual device checklist)**<br>' : ''}${by} |`);
}
lines.push('', '## Requirements', '', '| R | Level | Requirement | Acceptance criteria |', '|---|---|---|---|');
const reqs = [...spec.requirements.hard, ...spec.requirements.recommended, ...spec.requirements.optional];
for (const r of reqs) {
  const linked = acs.filter((a) => (a.requirements || []).includes(r.id)).map((a) => a.id);
  lines.push(`| ${r.id} | ${r.level} | ${r.text.replace(/\|/g, '/')} | ${linked.length ? linked.join(', ') : 'none (covered by design decisions / policy tests; see docs/DECISIONS.md)'} |`);
}
const missing = acs.filter((a) => !acHits[a.id].length).map((a) => a.id);
lines.push('', `Criteria with no test or script found: ${missing.length ? missing.join(', ') : 'none'}.`, '');
mkdirSync(join(root, 'docs/qa'), { recursive: true });
writeFileSync(join(root, 'docs/qa/TRACEABILITY.md'), lines.join('\n'));
console.log(`traceability: ${acs.length} criteria, ${reqs.length} requirements, ${missing.length} without a test`);
